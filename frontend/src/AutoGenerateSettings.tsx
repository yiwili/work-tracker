import { useCallback, useEffect, useMemo, useState } from "react";
import {
  AlertCircle,
  CheckCircle2,
  Clock3,
  LoaderCircle,
  Play,
  Plus,
  RefreshCw,
  SkipForward,
  X,
} from "lucide-react";
import type { AutoGenerateConfig, AutoGenerateStatus, Settings } from "./types";
import { api } from "./api";

export const DEFAULT_AUTO_GENERATE: AutoGenerateConfig = {
  enabled: false,
  mode: "daily_times",
  daily_times: ["18:00"],
  interval_minutes: 60,
  weekdays_only: false,
  collect_before_analyze: true,
  skip_if_unchanged: true,
  skip_if_confirmed: true,
};

const PRESET_DAILY_TIMES = ["09:30", "12:00", "18:00", "20:30"];
const PRESET_INTERVALS = [
  { minutes: 30, label: "30 分钟" },
  { minutes: 60, label: "1 小时" },
  { minutes: 120, label: "2 小时" },
  { minutes: 240, label: "4 小时" },
];

export function normalizeAutoGenerate(
  raw?: Partial<AutoGenerateConfig> | null,
): AutoGenerateConfig {
  const daily = Array.isArray(raw?.daily_times)
    ? Array.from(
        new Set(
          raw.daily_times
            .map((item) => String(item).trim())
            .filter((item) => /^\d{1,2}:\d{2}$/.test(item))
            .map((item) => {
              const [h, m] = item.split(":");
              return `${h.padStart(2, "0")}:${m}`;
            }),
        ),
      ).sort()
    : [...DEFAULT_AUTO_GENERATE.daily_times];

  const interval =
    typeof raw?.interval_minutes === "number" && Number.isFinite(raw.interval_minutes)
      ? Math.min(720, Math.max(15, Math.round(raw.interval_minutes)))
      : DEFAULT_AUTO_GENERATE.interval_minutes;

  return {
    enabled: Boolean(raw?.enabled ?? DEFAULT_AUTO_GENERATE.enabled),
    mode: raw?.mode === "interval" ? "interval" : "daily_times",
    daily_times: daily,
    interval_minutes: interval,
    weekdays_only: Boolean(raw?.weekdays_only ?? DEFAULT_AUTO_GENERATE.weekdays_only),
    collect_before_analyze: Boolean(
      raw?.collect_before_analyze ?? DEFAULT_AUTO_GENERATE.collect_before_analyze,
    ),
    skip_if_unchanged: Boolean(
      raw?.skip_if_unchanged ?? DEFAULT_AUTO_GENERATE.skip_if_unchanged,
    ),
    skip_if_confirmed: Boolean(
      raw?.skip_if_confirmed ?? DEFAULT_AUTO_GENERATE.skip_if_confirmed,
    ),
  };
}

function formatDateTime(iso: string | null | undefined, tz = "Asia/Shanghai"): string {
  if (!iso) return "暂无";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  try {
    return new Intl.DateTimeFormat("zh-CN", {
      timeZone: tz,
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      hour12: false,
    }).format(d);
  } catch {
    return iso;
  }
}

function formatStatusLabel(status?: AutoGenerateStatus | null): string {
  if (!status) return "读取中";
  if (status.running) return "正在执行";
  if (!status.enabled) return "未启用";
  if (!status.llm_enabled) return "等待开启模型";
  switch (status.last_status) {
    case "success":
      return "最近已生成";
    case "skipped":
      return "最近已跳过";
    case "error":
      return "执行失败";
    case "interrupted":
      return "上次执行中断";
    default:
      return "已就绪 · 等待下次触发";
  }
}

export function AutoGenerateSettings({
  settings,
  savedSettings,
  busy,
  onChange,
  onGoModelTab,
  onAutoGenerated,
}: {
  settings: Settings;
  savedSettings: Settings;
  busy: boolean;
  onChange: (next: Settings) => void;
  onGoModelTab: () => void;
  onAutoGenerated?: () => void;
}) {
  const cfg = useMemo(
    () => normalizeAutoGenerate(settings.auto_generate),
    [settings.auto_generate],
  );
  const savedCfg = useMemo(
    () => normalizeAutoGenerate(savedSettings.auto_generate),
    [savedSettings.auto_generate],
  );

  const [newTime, setNewTime] = useState("18:30");
  const [timeHint, setTimeHint] = useState("");
  const [intervalText, setIntervalText] = useState(() =>
    String(cfg.interval_minutes),
  );
  const [status, setStatus] = useState<AutoGenerateStatus | null>(null);
  const [loadingStatus, setLoadingStatus] = useState(false);
  const [triggerBusy, setTriggerBusy] = useState(false);
  const [runFeedback, setRunFeedback] = useState<{
    kind: "success" | "info" | "error";
    text: string;
  } | null>(null);

  useEffect(() => {
    setIntervalText(String(cfg.interval_minutes));
  }, [cfg.interval_minutes]);

  const updateCfg = (patch: Partial<AutoGenerateConfig>) => {
    setTimeHint("");
    onChange({
      ...settings,
      auto_generate: {
        ...cfg,
        ...patch,
      },
    });
  };

  const fetchStatus = useCallback(async (silent = false) => {
    if (!silent) setLoadingStatus(true);
    try {
      const res = await api<AutoGenerateStatus>("/auto-generate/status");
      setStatus(res);
    } catch {
      // Status card stays non-blocking if transient read fails
    } finally {
      if (!silent) setLoadingStatus(false);
    }
  }, []);

  useEffect(() => {
    void fetchStatus();
  }, [
    fetchStatus,
    savedSettings.auto_generate,
    savedSettings.llm_enabled,
    savedSettings.auto_import_analysis,
    savedSettings.timezone,
  ]);

  useEffect(() => {
    if (!status?.running && !savedCfg.enabled) return;
    const intervalMs = status?.running ? 4000 : 20000;
    const timer = window.setInterval(() => {
      void fetchStatus(true);
    }, intervalMs);
    return () => window.clearInterval(timer);
  }, [fetchStatus, status?.running, savedCfg.enabled]);

  const dirty =
    JSON.stringify(cfg) !== JSON.stringify(savedCfg) ||
    settings.llm_enabled !== savedSettings.llm_enabled ||
    settings.auto_import_analysis !== savedSettings.auto_import_analysis ||
    settings.timezone !== savedSettings.timezone;

  const addDailyTime = (rawValue: string) => {
    const trimmed = rawValue.trim();
    const match = /^(\d{1,2}):(\d{2})$/.exec(trimmed);
    if (!match) {
      setTimeHint("请输入有效时间（HH:MM）");
      return;
    }
    const hh = Number(match[1]);
    const mm = Number(match[2]);
    if (hh < 0 || hh > 23 || mm < 0 || mm > 59) {
      setTimeHint("时间范围需在 00:00 ~ 23:59");
      return;
    }
    const normalized = `${String(hh).padStart(2, "0")}:${String(mm).padStart(2, "0")}`;
    if (cfg.daily_times.includes(normalized)) {
      setTimeHint(`${normalized} 已在执行列表里`);
      return;
    }
    if (cfg.daily_times.length >= 12) {
      setTimeHint("最多支持配置 12 个每日执行时间");
      return;
    }
    updateCfg({
      daily_times: [...cfg.daily_times, normalized].sort(),
    });
  };

  const removeDailyTime = (value: string) => {
    updateCfg({
      daily_times: cfg.daily_times.filter((t) => t !== value),
    });
  };

  const handleRunNow = async () => {
    if (busy || triggerBusy || dirty) return;
    setTriggerBusy(true);
    setRunFeedback(null);
    try {
      const res = await api<{
        triggered: boolean;
        status_code: string;
        reason: string;
        status?: AutoGenerateStatus;
      }>("/auto-generate/run-now", "POST", {});
      if (res.status) setStatus(res.status);
      else await fetchStatus(true);
      setRunFeedback({
        kind: res.triggered ? "success" : "info",
        text: res.reason || "已执行完成",
      });
      onAutoGenerated?.();
    } catch (e) {
      setRunFeedback({
        kind: "error",
        text: (e as Error).message,
      });
      await fetchStatus(true);
    } finally {
      setTriggerBusy(false);
    }
  };

  return (
    <section className="settings-section auto-generate-section">
      <div className="auto-gen-head">
        <h2>
          <Clock3 size={19} /> 定时自动生成工作项
        </h2>
        <span
          className={`auto-gen-head-pill ${
            cfg.enabled && settings.llm_enabled
              ? "enabled"
              : cfg.enabled
                ? "pending"
                : "disabled"
          }`}
        >
          {cfg.enabled
            ? settings.llm_enabled
              ? "已启用"
              : "已开启（待开启模型）"
            : "未启用"}
        </span>
      </div>

      <p className="muted">
        {settings.auto_import_analysis
          ? "按计划在后台采集当天对话与 Git 提交，并将 AI 归纳结果直接填入「今日工作清单」（人工补录、已编辑或已锁定工时的条目会完整保留）。桌面端最小化到系统托盘时也会持续运行。"
          : "按计划在后台采集当天对话与 Git 提交，并生成工作项候选存入「分析结果」等待确认，不直接改动「今日工作清单」（若需全自动填入，可在上方勾选「AI 分析完成后直接填入今日工作清单」）。"}
      </p>

      {!settings.llm_enabled && (
        <div className="auto-gen-warning-banner" role="status">
          <AlertCircle size={16} />
          <span>
            当前尚未开启「模型分析」。建议先完成模型配置并开启，否则定时任务不会发送 AI 请求。
          </span>
          <button
            type="button"
            className="outline auto-gen-goto-model-btn"
            onClick={onGoModelTab}
          >
            去开启模型分析
          </button>
        </div>
      )}

      <label className="check-label">
        <input
          type="checkbox"
          checked={cfg.enabled}
          onChange={(e) => updateCfg({ enabled: e.target.checked })}
        />
        启用定时自动生成工作项
      </label>

      {cfg.enabled && (
        <div className="auto-gen-config-panel">
          <div className="auto-gen-field">
            <span className="auto-gen-label">触发频率</span>
            <div
              className="apple-segmented-group auto-gen-mode-switch"
              role="radiogroup"
              aria-label="定时触发方式"
            >
              <button
                type="button"
                role="radio"
                aria-checked={cfg.mode === "daily_times"}
                className={`apple-segmented-btn auto-gen-mode-btn ${
                  cfg.mode === "daily_times" ? "active" : ""
                }`}
                onClick={() => updateCfg({ mode: "daily_times" })}
              >
                每日固定时间
              </button>
              <button
                type="button"
                role="radio"
                aria-checked={cfg.mode === "interval"}
                className={`apple-segmented-btn auto-gen-mode-btn ${
                  cfg.mode === "interval" ? "active" : ""
                }`}
                onClick={() => updateCfg({ mode: "interval" })}
              >
                按固定间隔
              </button>
            </div>
          </div>

          {cfg.mode === "daily_times" ? (
            <div className="auto-gen-field">
              <span className="auto-gen-label">
                每日执行时间（{settings.timezone || "Asia/Shanghai"} · 24 小时制）
              </span>
              <div
                className="auto-gen-times-list"
                role="list"
                aria-label="已配置的每日执行时间"
              >
                {cfg.daily_times.length === 0 ? (
                  <span className="auto-gen-empty-times">
                    尚未选择时间，请至少添加 1 个时间点（如 18:00）
                  </span>
                ) : (
                  cfg.daily_times.map((t) => (
                    <span className="auto-gen-time-chip" key={t} role="listitem">
                      <Clock3 size={12} />
                      <strong>{t}</strong>
                      <button
                        type="button"
                        className="auto-gen-time-remove"
                        aria-label={`移除时间 ${t}`}
                        onClick={() => removeDailyTime(t)}
                      >
                        <X size={12} />
                      </button>
                    </span>
                  ))
                )}
              </div>

              <div className="auto-gen-presets">
                <span className="auto-gen-sub-label">常用时间：</span>
                {PRESET_DAILY_TIMES.map((preset) => {
                  const exists = cfg.daily_times.includes(preset);
                  return (
                    <button
                      key={preset}
                      type="button"
                      className={`auto-gen-chip ${exists ? "active" : ""}`}
                      onClick={() =>
                        exists ? removeDailyTime(preset) : addDailyTime(preset)
                      }
                    >
                      {preset}
                    </button>
                  );
                })}
              </div>

              <div className="auto-gen-add-row">
                <input
                  type="time"
                  aria-label="新增每日执行时间"
                  value={newTime}
                  onChange={(e) => {
                    setTimeHint("");
                    setNewTime(e.target.value);
                  }}
                />
                <button
                  type="button"
                  className="outline auto-gen-add-time-btn"
                  disabled={cfg.daily_times.length >= 12}
                  onClick={() => addDailyTime(newTime)}
                >
                  <Plus size={14} />
                  添加时间
                </button>
              </div>
              {timeHint && <p className="auto-gen-hint">{timeHint}</p>}
            </div>
          ) : (
            <div className="auto-gen-field">
              <div className="auto-gen-presets">
                <span className="auto-gen-sub-label">快捷间隔：</span>
                {PRESET_INTERVALS.map((p) => (
                  <button
                    key={p.minutes}
                    type="button"
                    className={`auto-gen-chip ${
                      cfg.interval_minutes === p.minutes ? "active" : ""
                    }`}
                    onClick={() => updateCfg({ interval_minutes: p.minutes })}
                  >
                    {p.label}
                  </button>
                ))}
              </div>
              <label className="auto-gen-interval-label">
                执行间隔（分钟，15 ~ 720）
                <input
                  type="number"
                  min={15}
                  max={720}
                  step={5}
                  required={cfg.enabled && cfg.mode === "interval"}
                  aria-label="执行间隔（分钟）"
                  value={intervalText}
                  onChange={(e) => {
                    const raw = e.target.value;
                    setIntervalText(raw);
                    if (raw.trim() === "") return;
                    const parsed = Number(raw);
                    if (Number.isInteger(parsed) && parsed >= 15 && parsed <= 720) {
                      updateCfg({ interval_minutes: parsed });
                    }
                  }}
                  onBlur={() => {
                    const parsed = Number(intervalText);
                    if (!Number.isFinite(parsed) || parsed < 15) {
                      setIntervalText("15");
                      updateCfg({ interval_minutes: 15 });
                    } else if (parsed > 720) {
                      setIntervalText("720");
                      updateCfg({ interval_minutes: 720 });
                    } else {
                      const rounded = Math.round(parsed);
                      setIntervalText(String(rounded));
                      updateCfg({ interval_minutes: rounded });
                    }
                  }}
                />
              </label>
            </div>
          )}

          <div className="auto-gen-guards">
            <label className="check-label">
              <input
                type="checkbox"
                checked={cfg.weekdays_only}
                onChange={(e) => updateCfg({ weekdays_only: e.target.checked })}
              />
              仅在工作日执行（周一至周五）
            </label>
            <label className="check-label">
              <input
                type="checkbox"
                checked={cfg.collect_before_analyze}
                onChange={(e) =>
                  updateCfg({ collect_before_analyze: e.target.checked })
                }
              />
              自动生成前先采集最新本地对话与 Git 提交
            </label>
            <label className="check-label">
              <input
                type="checkbox"
                checked={cfg.skip_if_unchanged}
                onChange={(e) =>
                  updateCfg({ skip_if_unchanged: e.target.checked })
                }
              />
              当天无新增对话或分析设置无变化时跳过（避免重复消耗 token）
            </label>
            <label className="check-label">
              <input
                type="checkbox"
                checked={cfg.skip_if_confirmed}
                onChange={(e) =>
                  updateCfg({ skip_if_confirmed: e.target.checked })
                }
              />
              当天日报确认完成后自动跳过
            </label>
          </div>
        </div>
      )}

      <div className="auto-gen-status-card" aria-label="定时自动生成运行状态">
        <div className="auto-gen-status-top">
          <div className="auto-gen-status-badge-row">
            <span
              className={`auto-gen-status-pill ${
                status?.running
                  ? "running"
                  : status?.last_status === "error"
                    ? "error"
                    : status?.last_status === "skipped"
                      ? "skipped"
                      : status?.last_status === "success"
                        ? "success"
                        : "idle"
              }`}
            >
              {status?.running ? (
                <LoaderCircle size={13} className="spin" />
              ) : status?.last_status === "error" ? (
                <AlertCircle size={13} />
              ) : status?.last_status === "skipped" ? (
                <SkipForward size={13} />
              ) : (
                <CheckCircle2 size={13} />
              )}
              {formatStatusLabel(status)}
            </span>
            {status?.target_date && (
              <span className="auto-gen-target-meta">
                作用日期：{status.target_date}
                {status.binding?.active
                  ? `（已绑定 ${status.binding.start_date.slice(5)} ~ ${status.binding.end_date.slice(5)}）`
                  : ""}
              </span>
            )}
          </div>

          <div className="auto-gen-status-actions">
            <button
              type="button"
              className="outline auto-gen-refresh-btn"
              disabled={loadingStatus}
              onClick={() => void fetchStatus(false)}
              title="刷新运行状态"
              aria-label="刷新定时自动生成状态"
            >
              <RefreshCw size={14} className={loadingStatus ? "spin" : ""} />
            </button>
            <button
              type="button"
              className="outline auto-gen-run-now-btn"
              disabled={
                busy ||
                triggerBusy ||
                dirty ||
                !savedSettings.llm_enabled ||
                Boolean(status?.running)
              }
              title={
                dirty
                  ? "当前设置尚未保存，请先点击「保存设置」"
                  : !savedSettings.llm_enabled
                    ? "请先开启模型分析"
                    : "立即执行一次自动采集与 AI 工作项生成"
              }
              onClick={() => void handleRunNow()}
            >
              {triggerBusy || status?.running ? (
                <LoaderCircle size={14} className="spin" />
              ) : (
                <Play size={14} />
              )}
              {triggerBusy || status?.running ? "正在执行…" : "立即执行一次"}
            </button>
          </div>
        </div>

        <div className="auto-gen-status-meta-grid">
          <div>
            <span>下次计划时间</span>
            <strong>
              {status?.enabled && status?.llm_enabled
                ? status.next_run_at
                  ? formatDateTime(status.next_run_at, status.timezone)
                  : "暂无可用窗口"
                : "未安排"}
            </strong>
          </div>
          <div>
            <span>上次成功生成</span>
            <strong>
              {status?.last_run_at
                ? formatDateTime(status.last_run_at, status.timezone)
                : "尚未运行"}
            </strong>
          </div>
          <div>
            <span>最近检查说明</span>
            <strong>{status?.last_reason || "尚无执行记录"}</strong>
          </div>
        </div>

        {dirty && (
          <p className="auto-gen-unsaved-note">
            当前定时或模型配置有未保存修改，请点击下方「保存设置」后使其生效或测试运行。
          </p>
        )}

        {status?.last_status === "error" && status.last_error && !runFeedback && (
          <div className="alert error compact" role="alert">
            <strong>最近一次后台执行出错</strong>
            <p>{status.last_error}</p>
          </div>
        )}

        {runFeedback && (
          <div
            className={`alert compact ${runFeedback.kind === "error" ? "error" : ""}`}
            role={runFeedback.kind === "error" ? "alert" : "status"}
          >
            {runFeedback.text}
          </div>
        )}
      </div>
    </section>
  );
}
